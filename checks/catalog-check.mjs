import assert from 'node:assert/strict';
import {PRODUCTS,productById,visibleProducts} from '../site/catalog.mjs';
import {CART_KEY,quantityValue,decodeCart,addItem,withQuantity,cartCount,cartTotal,createCartStore,decodeResult} from '../site/cart.mjs';
const original=[{id:'first-light',quantity:2}];
const mixed=addItem(original,'quiet-wood',1);
assert.equal(PRODUCTS.length,6);assert.equal(new Set(PRODUCTS.map(p=>p.id)).size,6);
assert.equal(cartTotal(mixed),213000);assert.equal(cartCount(mixed),3);
assert.deepEqual(original,[{id:'first-light',quantity:2}]);
assert.deepEqual(withQuantity(mixed,'first-light',0),[{id:'quiet-wood',quantity:1}]);
assert.deepEqual(withQuantity(mixed,'first-light',3),[{id:'first-light',quantity:3},{id:'quiet-wood',quantity:1}]);
assert.equal(addItem(mixed,'first-light',8),null);
assert.equal(addItem(mixed,'not-a-product',1),null);
for(const value of ['',0,10,-1,'1.5','1e0','two'])assert.equal(quantityValue(value),null);
assert.equal(quantityValue('9'),9);
assert.deepEqual(decodeCart('{"product":"first-light","quantity":1}'),[{id:'first-light',quantity:1}]);
assert.deepEqual(decodeCart('{"product":"first-light","quantity":0}'),[]);
assert.deepEqual(decodeCart(null),[]);
assert.deepEqual(decodeCart(JSON.stringify({version:2,items:mixed})),mixed);
for(const items of [[{id:'bad',quantity:1}],[{id:'first-light',quantity:10}],[{id:'first-light',quantity:'2'}],[...original,...original]])assert.throws(()=>decodeCart(JSON.stringify({version:2,items})));
assert.throws(()=>decodeCart('{bad'));
assert.equal(decodeResult(null),null);assert.equal(decodeResult('null'),null);
assert.equal(decodeResult('{"version":2,"items":[]}'),null);
assert.deepEqual(decodeResult('{"product":"first-light","quantity":2}').items,original);
assert.deepEqual(decodeResult(JSON.stringify({version:2,items:mixed})).items,mixed);
let saved='{"product":"first-light","quantity":1}';
const local=createCartStore(()=>({getItem:key=>saved,setItem:(key,value)=>{assert.equal(key,CART_KEY);saved=value;}}));
assert.equal(cartCount(local.read()),1);local.write(mixed);assert.equal(JSON.parse(saved).version,2);assert.deepEqual(local.read(),mixed);
const blocked=createCartStore(()=>{throw new Error('blocked');},original);
assert.deepEqual(blocked.read(),original);assert.equal(blocked.persistent,false);blocked.write(mixed);assert.deepEqual(blocked.read(),mixed);
const broken=createCartStore(()=>({getItem:()=>'{broken'}));assert.deepEqual(broken.read(),[]);assert.equal(broken.persistent,false);
assert.deepEqual(visibleProducts({family:'clean'}).map(p=>p.id),['first-light','soft-linen']);
assert.deepEqual(visibleProducts({query:'린넨'}).map(p=>p.id),['soft-linen']);
assert.deepEqual(visibleProducts({query:'quiet wood'}).map(p=>p.id),['quiet-wood']);
assert.equal(visibleProducts({query:'없는향'}).length,0);
assert.equal(visibleProducts({family:'woody',query:'비누'}).length,0);
assert.equal(visibleProducts({sort:'price-desc'})[0].id,'quiet-wood');
assert.equal(productById('first-light').price,69000);
console.log('PASS: six-product catalog, mixed totals, independent quantities/removal, legacy cart/result migration, invalid storage/schema, memory fallback, search/filter/sort.');
