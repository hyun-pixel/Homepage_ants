export function visibleProducts({family='all',query='',sort='featured'} = {}) {
  const term = query.trim().toLocaleLowerCase('ko-KR');
  const items = PRODUCTS.filter(p => (family === 'all' || p.family === family) && `${p.name} ${p.korean} ${p.scent} ${p.familyName} ${p.tags.join(' ')}`.toLocaleLowerCase('ko-KR').includes(term));
  if (sort === 'price-asc') items.sort((a,b) => a.price - b.price);
  if (sort === 'price-desc') items.sort((a,b) => b.price - a.price);
  return items;
}
